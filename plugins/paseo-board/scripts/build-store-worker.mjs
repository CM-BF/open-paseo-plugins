import { build } from "esbuild";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
const root = resolve(process.argv[2] || ".");
// Keep module provenance relative to this plugin, including linked development dependencies.
const result = await build({ absWorkingDir: root, preserveSymlinks: true, entryPoints: [resolve(root, "server/store-worker.ts")], bundle: true, platform: "node", format: "cjs", target: "node22", legalComments: "inline", metafile: true, write: false, logLevel: "silent" });
const target = resolve(root, "server/assets/store-worker.txt");
await mkdir(dirname(target), { recursive: true });
// Discover every package actually emitted, including nested dependency versions.
// Keep upstream license text intact; package paths in the inventory stay relative.
const packageRoots = new Set();
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, contribution] of Object.entries(output.inputs)) {
    if (!contribution.bytesInOutput) continue;
    const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)/);
    if (match) packageRoots.add(match[1]);
  }
}
const entries = [];
for (const relative of [...packageRoots].sort()) {
  const directory = resolve(root, relative);
  const pkg = JSON.parse(await readFile(resolve(directory, "package.json"), "utf8"));
  const licenseFiles = (await readdir(directory)).filter(name => /^(?:licen[cs]e|copying|notice)(?:[.-]|$)/i.test(name)).sort();
  let license;
  if (licenseFiles.length) {
    license = (await Promise.all(licenseFiles.map(async name => `${name}:\n${await readFile(resolve(directory, name), "utf8")}`))).join("\n");
  } else if (pkg.name === "@getpaseo/plugin") {
    // The published SDK omits a license file; its upstream attribution is retained here.
    license = "Copyright (c) 2025-present Mohamed Boudra\nLicensed under the Apache License, Version 2.0 (see LICENSE-APACHE-2.0).\n";
  } else {
    throw new Error(`Missing bundled dependency license: ${relative}`);
  }
  if (license.includes("*/")) throw new Error(`License cannot be embedded in a comment: ${relative}`);
  entries.push(`Includes ${pkg.name}@${pkg.version} (${relative}):\n${license}`);
}
const notices = `/*\nBundled dependency notices. Source license texts are reproduced below.\n\n${entries.join("\n")}\n*/\n`;
await writeFile(target, "// Generated by scripts/build-store-worker.mjs. Do not edit.\n" + notices + result.outputFiles[0].text);
console.log(`Board store worker: ${result.outputFiles[0].contents.length} bytes`);
