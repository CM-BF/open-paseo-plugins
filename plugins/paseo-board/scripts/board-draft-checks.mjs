// Dedicated BoardView draft recovery checks. The fixture retains only its mock
// server state; these tests exercise the production local draft store directly.
export async function runDurableDraftChecks(t) {
  const { assert, command, evaluate, until, frame, untilFrame, key, location, rightClickPoint, hostClick, hostLocation, openAt, sendText, submitCount, noPopover, input, popover, railClick, check, origin } = t;
  const draftOpen = '[data-testid="board-drafts-open"]';
  const shelf = '[data-testid="board-drafts"]';
  const value = () => evaluate(`document.querySelector(${JSON.stringify(input)})?.value`);
  const storedText = () => evaluate(`Object.keys(localStorage).filter(key=>key.startsWith('@paseo:board-drafts:')).map(key=>localStorage.getItem(key)).join('\\n')`);
  const imageSource = () => evaluate(`document.querySelector(${JSON.stringify(popover + ' img')})?.src`);
  const replaceInput = async text => {
    await hostClick(input);
    const focused = await evaluate(`document.activeElement===document.querySelector(${JSON.stringify(input)})`);
    if (!focused) console.log('DIAG draft-input-focus '+JSON.stringify(await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(input)}),r=e?.getBoundingClientRect();return {exists:!!e,disabled:e?.disabled,rect:r?.toJSON(),active:document.activeElement?.outerHTML?.slice(0,250),hit:r?document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)?.outerHTML?.slice(0,200):null,offline:!!document.querySelector('[data-testid="board-offline-draft"]'),shelf:!!document.querySelector('[data-testid="board-offline-drafts"]'),events:hostFixture.uiEvents.slice(-6)}})()`)));
    assert.equal(focused,true,'The real input must own focus before select-all');
    // Chromium's native editor command is required for macOS headless key input,
    // matching the existing canvas text-edit regression helper.
    await command('Input.dispatchKeyEvent',{type:'keyDown',key:'a',code:'KeyA',modifiers:4,commands:['selectAll']});
    await command('Input.dispatchKeyEvent',{type:'keyUp',key:'a',code:'KeyA',modifiers:0});
    assert.ok(await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(input)});return e.selectionStart===0&&e.selectionEnd===e.value.length})()`),'The real textarea selection must cover the whole previous value');
    await sendText(text);
  };
  const latestRequest = () => evaluate("hostFixture.calls.filter(item=>item.name==='board.interact').at(-1)?.input");
  const stable = () => evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  const reload = async (online = true) => {
    const previous = await evaluate('hostFixture.pageInstance');
    await command('Page.reload', { ignoreCache: true });
    await until(`window.hostFixture?.pageInstance && hostFixture.pageInstance!==${JSON.stringify(previous)} && ${online ? "hostFixture.mainReady()?.ready" : "true"}`);
    await until(online ? "document.querySelector('[data-testid=board-canvas-container]')" : "document.querySelector('[data-testid=board-offline-draft]')");
    await stable();
    assert.notEqual(await evaluate('hostFixture.pageInstance'), previous, 'A full page reload must create a fresh fixture and React/runtime heap');
  };
  const navigate = async (query = '') => {
    const previous = await evaluate('hostFixture.pageInstance');
    await command('Page.navigate', { url: origin + '/?drafts=1' + query });
    await until(`window.hostFixture?.pageInstance && hostFixture.pageInstance!==${JSON.stringify(previous)} && hostFixture.mainReady()?.ready`);
    await stable();
  };
  const discard = async () => {
    await hostClick('[data-testid="board-draft-discard"]');
    await noPopover();
  };
  const closeThread = async () => {
    const before = await submitCount();
    const canvas = await t.canvasRect();
    await t.clickPoint(canvas.x + canvas.width - 24, canvas.y + 24);
    await noPopover();
    assert.equal(await submitCount(), before, 'Dismissing a read-only thread cannot dispatch a message');
  };
  const openShelf = async () => { await hostClick(draftOpen); await until(`document.querySelector(${JSON.stringify(shelf)})`); };
  const restore = async text => {
    await openShelf();
    const selector = await evaluate(`(()=>{const rows=[...document.querySelectorAll('[data-testid^="board-draft-row-"]')];const row=rows.find(row=>row.textContent.includes(${JSON.stringify(text)}));if(!row)throw new Error('Draft row not found');return '[data-testid="'+row.getAttribute('data-testid')+'"] button[aria-label="继续编辑"]'})()`);
    await hostClick(selector);
    await until(`document.querySelector(${JSON.stringify(input)})`);
  };
  const pick = async selector => {
    const r = await location(selector), x = r.x + 8, y = r.y + 8;
    await command('Input.dispatchMouseEvent', {type:'mouseMoved',x,y,modifiers:12});
    await command('Input.dispatchMouseEvent', {type:'mousePressed',x,y,button:'left',clickCount:1,modifiers:12});
    await command('Input.dispatchMouseEvent', {type:'mouseReleased',x,y,button:'left',clickCount:1,modifiers:12});
    await untilFrame(`document.querySelector('[data-board-components]')?.shadowRoot.querySelector('[aria-current=true]')?.textContent===${JSON.stringify(selector)}`);
    return {x,y};
  };

  // Type before the asynchronous PNG completes, then prove the later pixels
  // reach durable storage without losing the text or changing the frozen target.
  await frame('pauseNextCapture()');
  const point = await pick('#point');
  await rightClickPoint(point.x + 10, point.y + 10);
  await until(`document.querySelector(${JSON.stringify(input)})`);
  await untilFrame('captureGate?.held===true');
  const firstText = '组件引用的草稿：刷新后还在';
  await sendText(firstText);
  const firstCompose = await evaluate("hostFixture.raw.filter(item=>item.type==='compose').at(-1).request");
  assert.equal(firstCompose.anchor.kind, 'element');
  assert.equal(firstCompose.anchor.selector, '#point');
  assert.equal(firstCompose.anchor.binding.target.id, 'point');
  assert.ok((await storedText()).includes(firstText));
  await frame('releaseCapture()');
  await until(`document.querySelector(${JSON.stringify(popover + ' img')})`);
  const firstImage = await imageSource();
  const firstAnchor = await evaluate("hostFixture.raw.filter(item=>item.type==='selection-capture'&&item.status==='ready').at(-1).anchor");
  assert.match(firstImage, /^data:image\/png;base64,/);
  await reload();
  await until(`document.querySelector(${JSON.stringify(input)})?.value===${JSON.stringify(firstText)}`);
  assert.equal(await imageSource(), firstImage);
  assert.equal(await submitCount(), 0);
  const position = await hostLocation(popover), canvas = await t.canvasRect();
  assert.ok(position.x >= canvas.x && position.y >= canvas.y, JSON.stringify({position,canvas}));
  assert.ok((await storedText()).includes('"point"'));
  check('a full page reload restores a typed component draft and its late real PNG, frozen component identity and placement without sending');

  await key('Escape'); await noPopover();
  await reload();
  assert.equal(await value(), undefined, 'A tucked-away draft stays tucked away after reload');
  assert.ok(await evaluate(`document.querySelector(${JSON.stringify(draftOpen)})?.textContent.includes('1')`));
  await openAt(420, 230); await sendText('第二个位置的独立草稿');
  await reload();
  await until(`document.querySelector(${JSON.stringify(input)})?.value==='第二个位置的独立草稿'`);
  await key('Escape'); await noPopover();
  await restore(firstText);
  assert.equal(await value(), firstText);
  assert.equal(await imageSource(), firstImage);
  await evaluate("hostFixture.mode('accept')");
  await hostClick('button[aria-label="主会话发送"]');
  await until(`!document.querySelector(${JSON.stringify(input)})`);
  const firstRequest = await latestRequest();
  assert.deepEqual(firstRequest.anchor, firstAnchor);
  assert.equal(firstRequest.text, firstText);
  assert.equal(await submitCount(), 1);
  await reload();
  assert.equal(await value(), undefined);
  assert.ok(await evaluate(`document.querySelector(${JSON.stringify(draftOpen)})?.textContent.includes('1')`));
  check('closing a composer preserves independent location drafts; explicit Send removes only its draft and transmits the exact frozen reference once');

  await navigate('&host=another-host');
  assert.equal(await value(), undefined);
  assert.equal(await evaluate(`!!document.querySelector(${JSON.stringify(draftOpen)})`), false);
  assert.equal(await submitCount(), 0);
  await navigate('&board=another-board');
  assert.equal(await value(), undefined);
  assert.equal(await evaluate(`!!document.querySelector(${JSON.stringify(draftOpen)})`), false);
  assert.equal(await submitCount(), 0);
  await navigate();
  await restore('第二个位置的独立草稿');
  assert.equal(await value(), '第二个位置的独立草稿');
  await discard(); await reload();
  assert.equal(await value(), undefined);
  assert.equal(await evaluate(`!!document.querySelector(${JSON.stringify(draftOpen)})`), false);
  check('draft collections are isolated by host and Board, and only explicit discard removes an unsent draft across a full reload');

  // An unknown send result must retain the immutable ID, payload, parent and
  // route. Restoring it may offer a retry but must never dispatch automatically.
  await railClick(firstRequest.intentId);
  await hostClick('button[aria-label="继续交流"]');
  const retryText = '原讨论的 Side 草稿与未知发送';
  await sendText(retryText);
  await evaluate("hostFixture.mode('held')");
  await key('Enter', 'Enter', 9);
  await until('hostFixture.pending().length===1');
  const uncertain = await latestRequest(), sendsBeforeReload = await submitCount();
  assert.equal(uncertain.destination, 'new-side');
  assert.equal(uncertain.sourceInteractionId, firstRequest.intentId);
  await reload();
  await until(`document.querySelector(${JSON.stringify(input)})?.value===${JSON.stringify(retryText)}`);
  assert.equal(await submitCount(), sendsBeforeReload);
  assert.ok(await evaluate("!!document.querySelector('button[aria-label=\"重试原发送\"]')"));
  await evaluate("hostFixture.mode('accept')");
  await hostClick('button[aria-label="重试原发送"]');
  await until(`!document.querySelector(${JSON.stringify(input)})`);
  assert.deepEqual(await latestRequest(), uncertain);
  assert.equal(await evaluate(`hostFixture.board().interactions.filter(item=>item.id===${JSON.stringify(uncertain.intentId)}).length`), 1);
  await reload();
  assert.equal(await value(), undefined);
  assert.equal(await submitCount(), sendsBeforeReload + 1);
  check('an in-flight send survives complete page loss as the exact intent, route and source thread; only a genuine retry sends it and success clears it');

  await openAt(); await sendText('已经落盘但响应丢失的消息');
  await evaluate("hostFixture.readFails(true);hostFixture.mode('lost-response')");
  await hostClick('button[aria-label="主会话发送"]');
  await until("document.querySelector('button[aria-label=\"重试原发送\"]')");
  const committed = await latestRequest(), committedCount = await submitCount();
  assert.ok(await evaluate(`hostFixture.board().interactions.some(item=>item.id===${JSON.stringify(committed.intentId)})`));
  const committedStoredAnchor = await evaluate(`(()=>{for(const k of Object.keys(localStorage)){if(!k.includes(':draft:'))continue;let r;try{r=JSON.parse(localStorage.getItem(k))}catch{continue}if(r.compose?.intentId===${JSON.stringify(committed.intentId)})return JSON.parse(localStorage.getItem(k.slice(0,k.lastIndexOf(':draft:'))+':anchor:'+r.context)).anchor}throw new Error('Missing durable send draft')})()`);
  assert.deepEqual(committedStoredAnchor, committed.anchor, 'Reconciliation compares the exact receipt semantically, independent of JSON key order');
  console.log('MEASURE durable-anchor-order '+JSON.stringify({request:Object.keys(committed.anchor),stored:Object.keys(committedStoredAnchor),stringIdentical:JSON.stringify(committed.anchor)===JSON.stringify(committedStoredAnchor)}));
  await evaluate('hostFixture.readFails(false)');
  await reload();
  await until(`!document.querySelector(${JSON.stringify(input)})`);
  assert.equal(await submitCount(), committedCount);
  assert.equal(await evaluate(`!!document.querySelector(${JSON.stringify(draftOpen)})`), false);
  await railClick(committed.intentId);
  assert.ok(await evaluate(`document.querySelector(${JSON.stringify(popover)}).textContent.includes('已经落盘但响应丢失的消息')`));
  await closeThread();
  check('a lost reply that already committed is reconciled with the durable interaction after reload, without a duplicate send or stale draft');

  await openAt(); await sendText('断线时继续写');
  await evaluate('hostFixture.eventDisconnect();hostFixture.readFails(true)');
  await sendText('，仍然保留在本机');
  assert.equal(await value(), '断线时继续写，仍然保留在本机');
  await evaluate('hostFixture.readFails(false)');
  await reload();
  await until(`document.querySelector(${JSON.stringify(input)})?.value==='断线时继续写，仍然保留在本机'`);
  assert.equal(await submitCount(), committedCount);
  await discard();
  check('a disconnected transport does not block local draft updates or cause automatic sends when the page reconnects');

  await openAt(); await sendText('本地写入失败时不能谎称已保存');
  await evaluate(`window.draftOriginalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(String(key).startsWith('@paseo:board-drafts:'))throw new DOMException('Fixture quota full','QuotaExceededError');return window.draftOriginalSetItem.call(this,key,value)}`);
  await sendText('，这一段仍可复制');
  await until(`document.querySelector('[role="alert"]')?.textContent.includes('草稿')`);
  assert.equal(await value(), '本地写入失败时不能谎称已保存，这一段仍可复制');
  const beforeFailedLeave=await evaluate('hostFixture.backCalls');
  await hostClick('button[aria-label="Boards"]');
  assert.equal(await evaluate('hostFixture.backCalls'),beforeFailedLeave);
  assert.equal(await value(),'本地写入失败时不能谎称已保存，这一段仍可复制');
  await evaluate('Storage.prototype.setItem=window.draftOriginalSetItem;delete window.draftOriginalSetItem');
  await hostClick(input); await sendText('，恢复后写入');
  await hostClick('button[aria-label="Boards"]');
  await until(`hostFixture.backCalls===${beforeFailedLeave+1}`);
  await reload();
  assert.equal(await value(),undefined);
  await restore('本地写入失败时不能谎称已保存，这一段仍可复制，恢复后写入');
  await reload();
  await until(`document.querySelector(${JSON.stringify(input)})?.value==='本地写入失败时不能谎称已保存，这一段仍可复制，恢复后写入'`);
  assert.equal(await submitCount(), committedCount);
  await discard();
  check('a real quota failure retains copyable text and blocks leaving Board; restored storage permits navigation and later recovery');

  await openAt(); await sendText('发送前必须持久记录同一次请求');
  await until(`document.querySelector(${JSON.stringify(popover + ' img')})`);
  await stable();
  const beforeBlockedSend = await submitCount();
  await evaluate(`window.draftOriginalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(String(key).startsWith('@paseo:board-drafts:'))throw new DOMException('Fixture intent quota full','QuotaExceededError');return window.draftOriginalSetItem.call(this,key,value)}`);
  await hostClick('button[aria-label="主会话发送"]');
  await until(`document.querySelector('[role="alert"]')?.textContent.includes('草稿')`);
  assert.equal(await submitCount(), beforeBlockedSend, 'A failed durable intent write cannot dispatch an unrecoverable message');
  assert.equal(await value(), '发送前必须持久记录同一次请求');
  console.log('DIAG quota-send '+JSON.stringify(await evaluate(`({buttons:[...document.querySelectorAll('[data-testid="board-local-popover"] button')].map(b=>({label:b.getAttribute('aria-label'),disabled:b.disabled})),active:document.activeElement?.tagName,uiEvents:hostFixture.uiEvents.slice(-9),captures:hostFixture.raw.filter(r=>r.type==='selection-capture').map(r=>({status:r.status,reason:r.reason})),records:Object.keys(localStorage).filter(k=>k.includes(':draft:')).map(k=>JSON.parse(localStorage.getItem(k))).map(r=>({text:r.compose.text,intent:r.compose.intentId,destination:r.compose.destination})),last:hostFixture.calls.filter(c=>c.name==='board.interact').at(-1)?.input.intentId})`)));
  await evaluate('Storage.prototype.setItem=window.draftOriginalSetItem;delete window.draftOriginalSetItem;hostFixture.mode("accept")');
  await hostClick('button[aria-label="重试原发送"]');
  await until(`!document.querySelector(${JSON.stringify(input)})`);
  assert.equal(await submitCount(), beforeBlockedSend + 1);
  await reload();
  assert.equal(await value(), undefined);
  check('a storage failure before send prevents the RPC, keeps the text recoverable and permits one explicit send after persistence succeeds');

  await closeThread();
  await frame('pauseNextCapture()'); await openAt();
  await untilFrame('captureGate?.held===true');
  await sendText('截图还没完成，文字不能丢');
  const beforePendingReload = await submitCount();
  await reload();
  await until(`document.querySelector(${JSON.stringify(input)})?.value==='截图还没完成，文字不能丢'`);
  assert.equal(await imageSource(), undefined);
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(popover)}).textContent.includes('截图准备中')`), false);
  assert.equal(await submitCount(), beforePendingReload);
  assert.equal(await evaluate("hostFixture.raw.some(item=>item.type==='selection-capture')"), false, 'Reload cannot resurrect a screenshot gesture or capture lease');
  await discard();
  check('reloading during screenshot capture retains text and the original location without fabricating pixels or reviving an expired capture');

  await openAt(); await sendText('完整草稿与损坏记录互不覆盖');
  await key('Escape'); await noPopover();
  const corruptKey = await evaluate(`(()=>{const current=Object.keys(localStorage).find(k=>k.startsWith('@paseo:board-drafts:')&&k.includes(':draft:'));if(!current)throw new Error('No draft to scope corruption');const key=current.slice(0,current.lastIndexOf(':draft:'))+':draft:fixture-corrupt';localStorage.setItem(key,'{broken-json');return key})()`);
  await reload(); await openShelf();
  assert.ok(await evaluate(`document.querySelector(${JSON.stringify(shelf)}).textContent.includes('无法读取')`));
  assert.equal(await evaluate(`localStorage.getItem(${JSON.stringify(corruptKey)})`), '{broken-json');
  await hostClick('[data-testid^="board-draft-row-"] button[aria-label="继续编辑"]');
  assert.equal(await value(), '完整草稿与损坏记录互不覆盖');
  assert.equal(await submitCount(), beforePendingReload);
  await discard();
  await evaluate(`localStorage.removeItem(${JSON.stringify(corruptKey)})`);
  check('an unreadable sibling record is reported and retained while valid drafts remain recoverable without sending or silently deleting corrupt data');

  await openAt(); await sendText('原始未知请求，保持不可变');
  await evaluate('hostFixture.mode("held")');
  await key('Enter', 'Enter', 9);
  await until('hostFixture.pending().length===1');
  const originalUnknown = await latestRequest();
  await evaluate('hostFixture.reject()');
  await until("document.querySelector('button[aria-label=\"重试原发送\"]')");
  await replaceInput('修改后的新草稿，等旧消息的迟到回执');
  assert.equal(await value(), '修改后的新草稿，等旧消息的迟到回执');
  await until(`document.querySelector(${JSON.stringify(draftOpen)})?.textContent.includes('2')`);
  const frozenUnknown = await evaluate(`Object.keys(localStorage).filter(k=>k.includes(':draft:')).map(k=>{try{return JSON.parse(localStorage.getItem(k))}catch{return null}}).find(r=>r?.compose?.intentId===${JSON.stringify(originalUnknown.intentId)})?.compose`);
  assert.equal(frozenUnknown.text, originalUnknown.text);
  assert.equal(frozenUnknown.destination, 'new-side');
  const countBeforeLate = await submitCount();
  const lateReceipt = { ...originalUnknown, id: originalUnknown.intentId, kind: 'fork', status: 'delivered', agentId: 'late-side-fixture', createdAt: new Date().toISOString(), updatedAt: new Date().toISOString(), resultReferences: [] };
  delete lateReceipt.boardId; delete lateReceipt.intentId;
  await evaluate(`hostFixture.seed([...hostFixture.board().interactions,${JSON.stringify(lateReceipt)}])`);
  await until(`document.querySelector(${JSON.stringify(draftOpen)})?.textContent.includes('1')`);
  assert.equal(await value(), '修改后的新草稿，等旧消息的迟到回执');
  assert.equal(await evaluate(`document.activeElement===document.querySelector(${JSON.stringify(input)})`), true);
  assert.equal(await submitCount(), countBeforeLate);
  await reload();
  await until(`document.querySelector(${JSON.stringify(input)})?.value==='修改后的新草稿，等旧消息的迟到回执'`);
  assert.equal(await submitCount(), countBeforeLate);
  await discard();
  check('editing an uncertain send preserves its immutable request separately; a late Side receipt removes only that request and cannot replace newer text or steal focus');

  await openAt(); await sendText('完整离线刷新也能继续编辑');
  await until(`document.querySelector(${JSON.stringify(popover + ' img')})`);
  const offlineImage = await imageSource(), sendsBeforeOffline = await submitCount();
  await evaluate('hostFixture.readFails(true);hostFixture.eventDisconnect()');
  await reload(false);
  assert.equal(await evaluate("!!document.querySelector('iframe[data-board-id]')"), false);
  assert.equal(await value(), '完整离线刷新也能继续编辑');
  assert.equal(await evaluate("document.querySelector('[data-testid=board-offline-draft] img')?.src"), offlineImage);
  await replaceInput('完全离线仍可写入的新文字');
  await key('Enter', 'Enter', 4);
  assert.equal(await submitCount(), sendsBeforeOffline);
  await reload(false);
  assert.equal(await value(), '完全离线仍可写入的新文字');
  assert.equal(await submitCount(), sendsBeforeOffline);
  await evaluate('hostFixture.readFails(false);hostFixture.refetch()');
  await until('hostFixture.mainReady()?.ready');
  assert.equal(await value(), '完全离线仍可写入的新文字');
  await evaluate('hostFixture.mode("accept")');
  await hostClick('button[aria-label="主会话发送"]');
  await until(`!document.querySelector(${JSON.stringify(input)})`);
  assert.equal(await submitCount(), sendsBeforeOffline + 1);
  assert.equal((await latestRequest()).anchor.image.data, offlineImage.split(',')[1]);
  check('with Board reads still failing across two complete reloads, the local draft and PNG remain editable; reconnecting sends only after an explicit click');

  await closeThread();
  await openAt(); await sendText('事件先确认但RPC尚未返回');
  await evaluate('hostFixture.mode("held")');
  await hostClick('button[aria-label="主会话发送"]');
  await until('hostFixture.pending().length===1');
  const eventFirst = await latestRequest(), beforeLateError = await submitCount();
  await evaluate('hostFixture.commitPending()');
  await until(`hostFixture.calls.filter(item=>item.name==='board.read').length>0 && document.querySelector('[data-testid="board-discussion-${eventFirst.intentId}"]')?.textContent.includes('已送达')`);
  assert.equal(await value(), '事件先确认但RPC尚未返回');
  await evaluate('hostFixture.reject()');
  await until(`!document.querySelector(${JSON.stringify(input)})`);
  assert.equal(await submitCount(), beforeLateError);
  assert.equal(await evaluate(`!!document.querySelector(${JSON.stringify(draftOpen)})`), false);
  check('an authoritative event arriving before a later RPC error clears the confirmed draft when sending unlocks, without waiting for another event or retry');

  await closeThread();
  await openAt(); await sendText('唯一草稿的引用损坏也需要提示');
  await key('Escape'); await noPopover();
  const onlyCorrupt = await evaluate(`(()=>{const k=Object.keys(localStorage).find(k=>k.includes(':draft:'));const r=JSON.parse(localStorage.getItem(k));const anchorKey=k.slice(0,k.lastIndexOf(':draft:'))+':anchor:'+r.context;localStorage.setItem(anchorKey,'{invalid-anchor');return {recordKey:k,anchorKey}})()`);
  await reload();
  assert.equal(await value(), undefined);
  await openShelf();
  assert.ok(await evaluate(`document.querySelector(${JSON.stringify(shelf)}).textContent.includes('无法读取')`));
  assert.equal(await evaluate(`localStorage.getItem(${JSON.stringify(onlyCorrupt.anchorKey)})`), '{invalid-anchor');
  assert.equal(await submitCount(), beforeLateError);
  await evaluate(`localStorage.removeItem(${JSON.stringify(onlyCorrupt.recordKey)});localStorage.removeItem(${JSON.stringify(onlyCorrupt.anchorKey)})`);
  check('even when its only draft has a corrupt reference, the Board retains a visible recovery notice and does not silently delete or dispatch that record');
}
