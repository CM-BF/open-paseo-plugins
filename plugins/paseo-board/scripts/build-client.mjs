// Prebuilds a Hermes-compatible client bundle for each plugin directory given on the command line.
//
// Paseo evaluates plugin client bundles from source with Hermes' runtime eval on iOS and Android.
// That compiler rejects `class` syntax (large bundles fail later with "Cannot read property
// 'prototype' of undefined"), treats let/const as var (no per-iteration loop bindings, no block
// shadowing) and rejects async generators. Metro lowers these for app code, but plugin bundles
// bypass Metro and the daemon's esbuild pass (target es2020) leaves them in place.
//
// For each plugin this writes:
//   client/hermes-bundle.js    index.client.tsx bundled by esbuild, then lowered by Babel
//   client/hermes-bundle.d.ts  its type
//   index.client.ts            re-exports the bundle; the daemon prefers it over index.client.tsx
//
// index.client.tsx stays the source of truth. Rebuild after editing client/ or shared/ code.
import { transformSync } from "@babel/core";
import { build } from "esbuild";
import { existsSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);

// Mirrors the daemon's client externals (@getpaseo/server plugins/compiler.js); the app supplies these.
const HOST_MODULES = [
  "@getpaseo/plugin",
  "@getpaseo/plugin/client",
  "@getpaseo/plugin/client/ui",
  "@getpaseo/plugin/client/react-native",
  "@tanstack/react-query",
  "react",
  "react/jsx-runtime",
  "react-native",
  "zod",
];

// The parts of @react-native/babel-preset that Hermes needs and esbuild's es2020 output still contains.
const BABEL_PLUGINS = [
  require("@babel/plugin-transform-classes"),
  require("@babel/plugin-transform-block-scoping"),
  require("@babel/plugin-transform-async-generator-functions"),
];

const WRAPPER = `// Hermes-compatible build of index.client.tsx, generated by scripts/build-client.mjs.
// The daemon loads index.client.ts before index.client.tsx; delete this file to load the source directly.
export { default } from "./client/hermes-bundle.js";
`;

const DECLARATION = `import type { PluginCleanup } from "@getpaseo/plugin";
import type { PluginClientContext } from "@getpaseo/plugin/client";

export default function contribute(client: PluginClientContext): PluginCleanup;
`;

export async function buildPlugin(pluginDirectory) {
  const entry = path.join(pluginDirectory, "index.client.tsx");
  if (!existsSync(entry)) return null;
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: "esm",
    jsx: "automatic",
    platform: "neutral",
    target: "es2020",
    mainFields: ["module", "main"],
    supported: { "async-await": false },
    external: HOST_MODULES,
    logLevel: "silent",
    treeShaking: true,
    write: false,
  });
  const lowered = transformSync(result.outputFiles[0].text, {
    babelrc: false,
    configFile: false,
    sourceType: "module",
    compact: false,
    plugins: BABEL_PLUGINS,
  });
  const bundle = `// Generated by scripts/build-client.mjs from index.client.tsx. Do not edit.\n${lowered.code}\n`;
  writeFileSync(path.join(pluginDirectory, "client", "hermes-bundle.js"), bundle);
  writeFileSync(path.join(pluginDirectory, "client", "hermes-bundle.d.ts"), DECLARATION);
  writeFileSync(path.join(pluginDirectory, "index.client.ts"), WRAPPER);
  return bundle.length;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  let failed = false;
  for (const directory of process.argv.slice(2)) {
    const id = path.basename(path.resolve(directory));
    try {
      const size = await buildPlugin(path.resolve(directory));
      console.log(size === null ? `${id}: no index.client.tsx, skipped` : `${id}: ${size} bytes`);
    } catch (error) {
      failed = true;
      console.error(`${id}: ${error.message}`);
    }
  }
  process.exitCode = failed ? 1 : 0;
}
