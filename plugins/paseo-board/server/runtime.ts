import { chmod, mkdir, rename, writeFile, lstat, symlink, readlink } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { homedir } from "node:os";
import { join } from "node:path";
import { z } from "zod";
import { CreateInputSchema, DecisionUpdateInputSchema, EmitInputSchema, IdSchema, PublishInputSchema, RespondInputSchema } from "../shared/contracts";
import { RUNTIME_SOURCE } from "./runtime-source";
import { skillMarkdown } from "./prompts";

export function runtimePaths(root = join(process.env.PASEO_HOME?.replace(/^~(?=\/|$)/, homedir()) || join(homedir(), ".paseo"), "paseo-board")) {
  return { root, socket: join(root, "bridge.sock"), bin: join(root, "bin"), cli: join(root, "bin", "paseo-board"), mcp: join(root, "bin", "paseo-board-mcp"), script: join(root, "lib", "client.mjs"), skillDir: join(root, "skills", "paseo-board"), skill: join(root, "skills", "paseo-board", "SKILL.md") };
}
export type RuntimePaths = ReturnType<typeof runtimePaths>;
export const shellQuote = (text: string) => `'${text.replaceAll("'", `'\\''`)}'`;

export function toolDefinitions() {
  const withFile = { htmlFile: z.string().describe("Absolute local HTML file; omit html when using this") };
  const entries = [
    ["list", "List boards owned by you or shared with your discussion fork.", z.object({ workspaceId: z.string().optional() })],
    ["read", "Read the free canvas, latest revision, decisions and user interactions. Read before publishing.", z.object({ boardId: IdSchema })],
    ["create", "Create your persistent, fully interactive HTML/JS board. Task content and layout are completely free.", CreateInputSchema.extend({ htmlFile: withFile.htmlFile.optional() })],
    ["publish", "Update data, insert/replace a local HTML/JS component, or explicitly replace a full document. Preserve other controls with a patch. Link fulfilled user intents to real results.", PublishInputSchema.extend({ htmlFile: withFile.htmlFile.optional() })],
    ["respond", "Answer your assigned interaction at its original question marker with text and optional fully interactive HTML/JS. This cannot change the source canvas or another agent's answer. Read the interaction responseRevision first (missing means 0).", RespondInputSchema.extend({ htmlFile: withFile.htmlFile.optional() })],
    ["decision", "Record a consequential default decision YOU made, with stated rationale, impact and evidence. Never misattribute user requirements or guess hidden reasons.", DecisionUpdateInputSchema],
    ["emit", "Save an external fact/data update without waking any agent. Use a stable eventId for retry; optionally track an observation whose value changes become evidenced candidates.", EmitInputSchema],
  ] as const;
  return entries.map(([name, description, schema]) => ({ name: `board_${name}`, description, inputSchema: z.toJSONSchema(schema, { io: "input" }) }));
}

function launcher(paths: RuntimePaths, mode: "cli" | "mcp"): string {
  return `#!/bin/sh
# Generated by paseo-board. Stable path survives plugin updates.
PASEO_BOARD_HOME=${shellQuote(paths.root)}
export PASEO_BOARD_HOME
board_node=${shellQuote(process.execPath)}
if [ ! -x "$board_node" ]; then
  echo 'Paseo Board Node runtime disappeared; reload this plugin to regenerate its launcher.' >&2
  exit 3
fi
${typeof process.versions.electron === "string" ? "ELECTRON_RUN_AS_NODE=1 " : ""}exec "$board_node" ${shellQuote(paths.script)} ${mode} "$@"
`;
}
async function atomic(path: string, text: string, mode = 0o600): Promise<void> {
  const temp = `${path}.${randomUUID()}.tmp`;
  await writeFile(temp, text, { mode }); await rename(temp, path); await chmod(path, mode);
}
export async function writeRuntime(paths: RuntimePaths): Promise<void> {
  await Promise.all([paths.root, paths.bin, join(paths.root, "lib"), paths.skillDir].map((path) => mkdir(path, { recursive: true, mode: 0o700 })));
  await atomic(paths.script, RUNTIME_SOURCE.replace("__BOARD_TOOL_DEFINITIONS__", JSON.stringify(toolDefinitions())));
  await atomic(paths.cli, launcher(paths, "cli"), 0o700);
  await atomic(paths.mcp, launcher(paths, "mcp"), 0o700);
  await atomic(paths.skill, skillMarkdown(paths.cli));
}
/** Only create missing skill links. Never replace a user's existing skill or another installation. */
export async function linkSkills(paths: RuntimePaths, home = homedir()): Promise<void> {
  for (const directory of [join(home, ".agents", "skills"), join(home, ".claude", "skills"), join(home, ".codex", "skills")]) {
    const link = join(directory, "paseo-board");
    try { const stat = await lstat(link); if (stat.isSymbolicLink()) await readlink(link); continue; }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
    await mkdir(directory, { recursive: true });
    await symlink(paths.skillDir, link);
  }
}
