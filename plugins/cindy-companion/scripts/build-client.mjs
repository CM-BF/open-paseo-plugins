// Paseo evaluates plugin contributions directly on Hermes as well as in browsers.
// Keep the original HTML document as data while lowering the host contribution's syntax.
import { transformSync } from '@babel/core';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const directory = fileURLToPath(new URL('../', import.meta.url));
const external = ['@getpaseo/plugin', '@getpaseo/plugin/client', '@getpaseo/plugin/client/ui',
  '@getpaseo/plugin/client/react-native', '@tanstack/react-query', 'react', 'react/jsx-runtime', 'react-native', 'zod'];
const output = await build({ entryPoints: [join(directory, 'index.client.tsx')], bundle: true, write: false,
  format: 'esm', platform: 'neutral', jsx: 'automatic', target: 'es2020', mainFields: ['module', 'main'],
  supported: { 'async-await': false }, external, treeShaking: true, logLevel: 'silent' });
const lowered = transformSync(output.outputFiles[0].text, { babelrc: false, configFile: false,
  sourceType: 'module', compact: false, plugins: [require('@babel/plugin-transform-classes'),
    require('@babel/plugin-transform-block-scoping'), require('@babel/plugin-transform-async-generator-functions')] });
if (!lowered?.code) throw new Error('The client build returned no code');
await writeFile(join(directory, 'client/hermes-bundle.js'), '// Generated by scripts/build-client.mjs; do not edit.\n' + lowered.code + '\n');
await writeFile(join(directory, 'client/hermes-bundle.d.ts'), 'import type { PluginCleanup } from "@getpaseo/plugin";\nimport type { PluginClientContext } from "@getpaseo/plugin/client";\nexport default function contribute(client: PluginClientContext): PluginCleanup;\n');
await writeFile(join(directory, 'index.client.ts'), '// Generated entry for Hermes and web. Source: index.client.tsx.\nexport { default } from "./client/hermes-bundle.js";\n');
console.log(`Client bundle: ${Buffer.byteLength(lowered.code)} bytes`);
