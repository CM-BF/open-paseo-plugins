import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

async function writeGenerated(filename, content) {
  if(await fs.readFile(filename,'utf8').catch(()=>null)===content)return;
  await fs.writeFile(`${filename}.tmp`,content);
  await fs.rename(`${filename}.tmp`,filename);
}
export async function generateFontAssets(plugin) {
  const source=JSON.parse(await fs.readFile(path.join(plugin,'web/assets/fonts/SOURCE.json'),'utf8'));
  const manifest={},assets={};
  for(const font of ['Regular','Medium','Semibold']) {
    const filename=`HarmonyOS_SansSC_${font}.ttf`;
    const bytes=await fs.readFile(path.join(plugin,'web/assets/fonts',filename));
    const sha256=crypto.createHash('sha256').update(bytes).digest('hex');
    if(sha256!==source.files[filename])throw new Error(`Original font bytes changed: ${filename}`);
    manifest[font]={size:bytes.length,sha256};
    assets[font]={data:bytes.toString('base64'),...manifest[font]};
  }
  await fs.mkdir(path.join(plugin,'server/generated'),{recursive:true});
  await writeGenerated(path.join(plugin,'shared/font-manifest.ts'),`// Generated from official unmodified Huawei fonts; see web/assets/fonts/SOURCE.json.\nexport const FONT_MANIFEST = ${JSON.stringify(manifest,null,2)} as const;\nexport type FontWeightName = keyof typeof FONT_MANIFEST;\nexport const FONT_CHUNK_BYTES = 393216;\n`);
  const rows=Object.entries(assets).map(([name,value])=>`${name}: Object.freeze(${JSON.stringify(value)})`).join(',\n');
  await writeGenerated(path.join(plugin,'server/generated/font-assets.ts'),`// Generated by scripts/generate-font-assets.mjs; server-only original font bytes.\n// Copyright 2021-2025 Huawei Device Co., Ltd. All Rights Reserved.\n// Complete agreement: web/licenses/HarmonyOS-Sans-LICENSE_Fonts.\nimport type { FontWeightName } from '../../shared/font-manifest';\nexport const FONT_ASSETS: Readonly<Record<FontWeightName, { readonly data: string; readonly size: number; readonly sha256: string }>> = Object.freeze({\n${rows}\n});\n`);
  return manifest;
}
