import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { webDependencyAliases, assertSingleWebRuntime } from './web-bundle-policy.mjs';
import { compressSettingsHtml } from './compress-settings.mjs';
import { generateFontAssets } from './generate-font-assets.mjs';
const plugin=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const web=path.join(plugin,'web');
const require=createRequire(path.join(web,'package.json'));
const esbuild=require('esbuild');
const postcss=require('postcss');
const tailwindcss=require('tailwindcss');
const autoprefixer=require('autoprefixer');
const aliases=JSON.parse(await fs.readFile(path.join(web,'aliases.json'),'utf8'));
const renderer=path.join(plugin,'vendor/renderer');
const packageAliases={
  '@cindy/maker-shared/model-route':path.join(plugin,'vendor/shared/upstream/modelRoute.ts'),
  '@cindy/maker-shared':path.join(plugin,'vendor/shared/upstream/scheduleInterval.ts'),
  '@cindy/maker-scheduler/cron':path.join(plugin,'vendor/shared/upstream/cron.ts'),
  '@paseo/frame-storage':path.join(web,'frame-storage.ts'),
};
await generateFontAssets(plugin);
const configBuild=await esbuild.build({entryPoints:[path.join(web,'tailwind.config.ts')],bundle:true,platform:'node',format:'cjs',write:false});
const configModule={exports:{}};new Function('module','exports','require',configBuild.outputFiles[0].text)(configModule,configModule.exports,require);
const tailwindConfig=configModule.exports.default??configModule.exports;
tailwindConfig.content=[path.join(renderer,'**/*.{ts,tsx}'),path.join(web,'*.{ts,tsx}'),path.join(web,'adapters/**/*.{ts,tsx}')];
const result=await esbuild.build({
 absWorkingDir:plugin,alias:webDependencyAliases(web),
 entryPoints:[path.join(web,'index.tsx')],outdir:path.join(web,'.build'),bundle:true,write:false,format:'iife',platform:'browser',target:['es2022'],minify:true,metafile:true,jsx:'automatic',
 nodePaths:[path.join(web,'node_modules')],define:{'process.env.NODE_ENV':'"production"'},loader:{'.png':'dataurl','.jpg':'dataurl','.jpeg':'dataurl','.svg':'dataurl','.woff':'dataurl','.woff2':'dataurl','.ttf':'dataurl'},
 plugins:[{name:'cindy-host-seams',setup(build){build.onResolve({filter:/.*/},args=>{
  if(packageAliases[args.path])return{path:packageAliases[args.path]};
  if(args.path.startsWith('@cindy-assets/'))return{path:path.join(web,'assets',args.path.slice(14))};
  let absolute=args.path.startsWith('@/')?path.join(renderer,args.path.slice(2)):args.path.startsWith('.')?path.resolve(args.resolveDir,args.path):null;
  if(absolute?.startsWith(renderer+path.sep)){
   const key=path.relative(renderer,absolute).replace(/\\/g,'/').replace(/\.(tsx?|js)$/,'');
   if(aliases[key])return{path:path.join(web,'adapters',aliases[key])};
  }
  if(args.path.startsWith('@/')) return build.resolve(absolute,{resolveDir:args.resolveDir,kind:args.kind});
  return undefined;
 });}}],
});
assertSingleWebRuntime(result.metafile,plugin,web,['react','react-dom','react-router','react-router-dom']);
const js=result.outputFiles.find(file=>file.path.endsWith('.js'))?.text;
const cssInput=result.outputFiles.find(file=>file.path.endsWith('.css'))?.text??'';
if(!js)throw new Error('No settings JavaScript generated');
if(Object.keys(result.metafile.inputs).some(input=>input.includes('server/generated/font-assets')||/HarmonyOS_SansSC_.*\.ttf$/.test(input)))throw new Error('Original fonts must remain server-only chunk assets');
const css=(await postcss([tailwindcss(tailwindConfig),autoprefixer]).process(cssInput,{from:undefined})).css;
const html=`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Cindy Settings</title><style>${css.replaceAll('</style','<\\/style')}</style></head><body><div id="root"></div><script>${js.replaceAll('</script','<\\/script')}</script></body></html>`;
const bootstrap=compressSettingsHtml(html);
if(Buffer.byteLength(bootstrap)>20*1024*1024)throw new Error('Compressed settings document exceeds the 20 MiB transport budget');
const generated=path.join(plugin,'client/generated');await fs.mkdir(generated,{recursive:true});
await fs.writeFile(path.join(generated,'settings-html.ts'),`// Generated by scripts/build-web.mjs; do not edit.\nexport const SETTINGS_HTML = ${JSON.stringify(bootstrap)};\n`);
await fs.mkdir(path.join(web,'.build'),{recursive:true});
await fs.writeFile(path.join(web,'.build/settings.html'),html);
await fs.writeFile(path.join(web,'.build/bootstrap.html'),bootstrap);
await fs.writeFile(path.join(web,'.build/meta.json'),JSON.stringify(result.metafile,null,2));
console.log(`Cindy settings HTML: ${(Buffer.byteLength(html)/1024/1024).toFixed(2)} MiB; sha256 ${crypto.createHash('sha256').update(html).digest('hex')}`);
console.log(`Transport bootstrap: ${Buffer.byteLength(bootstrap)} bytes; sha256 ${crypto.createHash('sha256').update(bootstrap).digest('hex')}`);
